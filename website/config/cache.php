    /*
    |--------------------------------------------------------------------------
    | Production Cache Store Recommendation
    |--------------------------------------------------------------------------
    |
    | The default is 'database' which works out of the box for development and
    | small deployments.  For production, switch to 'redis' by setting:
    |
    |     CACHE_STORE=redis
    |
    | Why Redis over database-backed cache?
    |
    | 1. Contention: MySQL/MariaDB is already handling OLTP queries, queue jobs,
    |    and session storage.  Adding cache reads/writes to the same connection
    |    pool increases lock contention on the cache table and steals InnoDB
    |    buffer pool pages from your real data.
    |
    | 2. Latency: Redis serves reads in ~0.1 ms (memory-only, single-threaded
    |    event loop) vs. ~1-5 ms for a database SELECT with network round-trip.
    |    For data cached on every request (workspace settings, plan features),
    |    this compounds into meaningful p95 savings.
    |
    | 3. Eviction: Redis LRU eviction is automatic.  The database cache table
    |    grows unbounded and requires periodic pruning via `cache:prune-stale-tags`
    |    or a scheduled `cache:clear`.
    |
    | 4. Atomic operations: Redis SETNX prevents cache stampedes natively.
    |    Database-backed cache relies on advisory locks that vary by driver.
    |
    | In short: let MySQL handle your data, let Redis handle your cache + queue
    | + sessions.  They are purpose-built for different access patterns.
    |
    */

